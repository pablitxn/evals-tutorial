/** Compile authoritative wire schemas ahead of time: browser CSP needs no eval. */
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import Ajv from 'ajv';
import standaloneCode from 'ajv/dist/standalone/index.js';
import { root } from './lib.mjs';
const schema=JSON.parse(readFileSync(resolve(root,'packages/contracts/schema/v1.json'),'utf8'));
const ajv=new Ajv({allErrors:true,strict:false,strictNumbers:true,code:{source:true,esm:true}});
ajv.addSchema(schema);
const names=Object.keys(schema.$defs);
const exports=Object.fromEntries(names.map(name=>[name,`${schema.$id}#/$defs/${name}`]));
let source=standaloneCode(ajv,exports);
const helper='require("ajv/dist/runtime/ucs2length").default';
source=source.replaceAll(helper,'unicodeLength');
if(source.includes('require(')) throw new Error('Unreviewed standalone runtime import');
source='// Generated by scripts/generate-validators.mjs. Do not edit.\n'+
  'import unicodeLengthModule from "ajv/dist/runtime/ucs2length.js";\n'+
  'const unicodeLength = typeof unicodeLengthModule === "function" ? unicodeLengthModule : unicodeLengthModule.default;\n'+source+'\n';
const declaration='// Generated by scripts/generate-validators.mjs. Do not edit.\nimport type { ValidateFunction } from "ajv";\n'+names.map(name=>`export const ${name}: ValidateFunction;`).join('\n')+'\n';
for(const [path,expected] of [['packages/contracts/src/validators.generated.mjs',source],['packages/contracts/src/validators.generated.d.mts',declaration]]){
 const target=resolve(root,path);
 if(process.argv.includes('--check')){if(readFileSync(target,'utf8')!==expected)throw new Error(`Generated validator drift: ${path}`);}
 else writeFileSync(target,expected);
}
