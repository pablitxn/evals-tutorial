"""Generate type declarations from the authoritative JSON Schema subset."""
import json
import sys
from pathlib import Path
root=Path(__file__).resolve().parents[1]
defs=json.loads((root/'packages/contracts/schema/v1.json').read_text())['$defs']

def ts(s):
    if '$ref' in s:return s['$ref'].split('/')[-1]
    if 'const' in s:return json.dumps(s['const'])
    if 'enum' in s:return ' | '.join(json.dumps(x) for x in s['enum'])
    for union in ('anyOf','oneOf'):
        if union in s:return ' | '.join('('+ts(v)+')' for v in s[union])
    t=s.get('type')
    if t=='array':return 'Array<'+ts(s['items'])+'>'
    if t=='object':
        if 'properties' in s:return '{\n'+''.join('  '+k+('' if k in s.get('required',[]) else '?')+': '+ts(v)+';\n' for k,v in s['properties'].items())+'}'
        return '{ [key: string]: '+ts(s['additionalProperties'])+' }'
    return {'string':'string','number':'number','integer':'number','boolean':'boolean','null':'null'}[t]

extra={}
def py(s,name):
    if '$ref' in s:return s['$ref'].split('/')[-1]
    if 'const' in s:return 'Literal['+repr(s['const'])+']'
    if 'enum' in s:return 'Literal['+', '.join(repr(x) for x in s['enum'])+']'
    for union in ('anyOf','oneOf'):
        if union in s:return ' | '.join(py(v,name+str(i)) for i,v in enumerate(s[union]))
    t=s.get('type')
    if t=='array':return 'list['+py(s['items'],name+'Item')+']'
    if t=='object':
        if 'properties' in s:
            lines=[]
            for k,v in s['properties'].items():
                typ=py(v,name+k[0].upper()+k[1:])
                if k not in s.get('required',[]):typ='NotRequired['+typ+']'
                lines.append('    '+k+': '+typ)
            extra[name]='class '+name+'(TypedDict):\n'+'\n'.join(lines or ['    pass'])+'\n'
            return name
        return 'dict[str, '+py(s['additionalProperties'],name+'Value')+']'
    return {'string':'str','number':'float','integer':'int','boolean':'bool','null':'None'}[t]

tsout='// Generated by scripts/generate-contracts.py. Do not edit.\n'+''.join('export type '+name+' = '+ts(s)+';\n\n' for name,s in defs.items())
pyout='# Generated by scripts/generate-contracts.py. Do not edit.\nfrom __future__ import annotations\nfrom typing import Literal, NotRequired, TypedDict\n\n'
for name,s in defs.items():
    typ=py(s,name)
    if typ != name:pyout+='type '+name+' = '+typ+'\n'
pyout+='\n'+'\n'.join(extra.values())
for path,data in [(root/'packages/contracts/src/generated.ts',tsout),(root/'packages/contracts/python/tutorial_contracts/generated.py',pyout)]:
    if '--check' in sys.argv:
        if not path.exists() or path.read_text()!=data:raise SystemExit(f'Generated contract drift: {path.relative_to(root)}')
    else:path.write_text(data)
